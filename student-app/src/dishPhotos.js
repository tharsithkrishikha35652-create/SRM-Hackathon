export function photoForMenuMeal(meal, weekday, dietary = 'non_veg') {
  const isVeg = dietary === 'veg';
  if (weekday === 'saturday' && meal.id === 'snacks') return DISH_PHOTOS.groundnuts;
  if (weekday === 'wednesday' && meal.id === 'lunch' && isVeg) return DISH_PHOTOS.gheeRice;
  if (weekday === 'thursday' && meal.id === 'lunch' && isVeg) return DISH_PHOTOS.sambar;
  if (weekday === 'sunday' && meal.id === 'breakfast' && isVeg) return DISH_PHOTOS.breadToast;
  if (weekday === 'sunday' && meal.id === 'lunch' && isVeg) return DISH_PHOTOS.vegBiryani;
  if (weekday === 'friday' && meal.id === 'dinner' && isVeg) return DISH_PHOTOS.vegPulao;

  const mainDish = MAIN_DISH_BY_WEEKLY_MENU[weekday]?.[meal.id];
  if (mainDish && DISH_PHOTOS[mainDish]) return DISH_PHOTOS[mainDish];

  const firstMatch = ITEM_OVERRIDES.find(item => meal.items?.some(name => item.pattern.test(name)));
  return firstMatch ? DISH_PHOTOS[firstMatch.key] || DISH_PHOTOS.upma : DISH_PHOTOS.upma;
}